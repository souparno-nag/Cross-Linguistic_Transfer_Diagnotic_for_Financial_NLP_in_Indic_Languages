"""T-701 — label-share table for every cell of the grid (CLAUDE7.md).

    python -m scripts.t701_shares
    python -m scripts.t701_shares --n-boot 200     # faster draft

Writes `reports/phase7/label_shares.{parquet,md}`: for each of the 72 cells
(task × encoder × condition), the share of failed (item, seed) rows carrying
each level-1 and level-2 label, pooled with a bootstrap 95% CI and per seed as
mean ± std, beside the cell's failure count and failure rate.

Exits non-zero if a cell is missing, if the labels do not reconcile with
Phase 3's failure sets row for row, or if any level's shares fail to sum to
100% (CLAUDE7.md T-701). CPU only.
"""

from __future__ import annotations

import argparse
import sys

import pandas as pd

from scripts.t408_source_comparison import find_nonconverged
from src import findings as F
from src.download_dataset.paths import REPO_ROOT
from src.env_check import require_python

OUT_DIR = REPO_ROOT / "reports" / "phase7"
CELL_KEYS = ["task", "encoder", "kind", "condition_id", "source", "target"]


def build(n_boot: int) -> tuple[pd.DataFrame, list[str]]:
    rows, evaluated, problems = F.load_all(find_nonconverged())

    tables = [F.grouped_shares(rows, CELL_KEYS, n_boot=n_boot).assign(seed_set="all")]
    affected_keys = rows.loc[rows["untrained"], ["task", "encoder", "condition_id"]].drop_duplicates()
    if len(affected_keys):
        kept = rows[~rows["untrained"]].merge(affected_keys, on=["task", "encoder", "condition_id"])
        tables.append(F.grouped_shares(kept, CELL_KEYS, n_boot=n_boot).assign(seed_set="converged"))
    table = pd.concat(tables, ignore_index=True)

    # failure counts as rates
    fails = rows.groupby(["task", "encoder", "condition_id", "seed"]).size().rename("n_failures_seed").reset_index()
    per_seed = evaluated.merge(fails, on=["task", "encoder", "condition_id", "seed"], how="left").fillna(
        {"n_failures_seed": 0}
    )
    per_seed["rate"] = per_seed["n_failures_seed"] / per_seed["n_evaluated"]
    volume = per_seed.groupby(["task", "encoder", "condition_id"]).agg(
        n_evaluated=("n_evaluated", "sum"),
        n_failed=("n_failures_seed", "sum"),
        rate_seed_mean=("rate", "mean"),
        rate_seed_std=("rate", "std"),
    ).reset_index()
    volume["failure_rate"] = volume["n_failed"] / volume["n_evaluated"]
    table = table.merge(
        volume[["task", "encoder", "condition_id", "n_evaluated", "failure_rate", "rate_seed_mean", "rate_seed_std"]],
        on=["task", "encoder", "condition_id"],
        how="left",
    )

    n_cells = table.loc[table["seed_set"] == "all", ["task", "encoder", "condition_id"]].drop_duplicates()
    expected = len(F.TASKS) * len(F.ENCODERS) * 18
    if len(n_cells) != expected:
        problems.append(f"{len(n_cells)} cells, expected {expected}")
    problems += F.check_shares_sum(table, ["seed_set"] + CELL_KEYS)
    return table, problems


def render(table: pd.DataFrame, config_hash: str) -> str:
    lines = [
        "# Phase 7 — label shares per cell (T-701)",
        "",
        f"Config hash `{config_hash}`. Generated by `python -m scripts.t701_shares`.",
        "",
        "Each cell's failed (item, seed) rows, split by the label Phase 6 assigned. **Shares are of "
        "failures, not of all predictions** (CLAUDE7.md, decided 2026-10-13). Level 1 shows the pooled "
        "share with its bootstrap 95% CI (clusters of condition and item); the per-seed spread is in the "
        "parquet. `fail rate` is failed rows over evaluated rows, all seeds.",
        "",
        "Two labels carry a stated limitation (CLAUDE7.md hard rule 4):",
        "",
        *F.caveat_lines(),
        "",
    ]
    all_ = table[table["seed_set"] == "all"]
    for (task, encoder), cell in all_.groupby(["task", "encoder"]):
        lines += [f"## Task {task} — {encoder}", "", "### Level 1", ""]
        lines += [
            "| condition | failures | fail rate | unattributed | linguistic | data | model |",
            "|---|---|---|---|---|---|---|",
        ]
        for condition, c in cell.groupby("condition_id", sort=True):
            l1 = c[c["level"] == "L1"].set_index("measure")
            lines.append(
                f"| {condition} | {int(l1['n_failures'].iloc[0]):,} | {F.pct(l1['failure_rate'].iloc[0])} | "
                + " | ".join(
                    F.pct_ci(l1.loc[g, "share"], l1.loc[g, "ci_low"], l1.loc[g, "ci_high"])
                    for g in ["unattributed", "linguistic", "data", "model"]
                )
                + " |"
            )
        labels = [label for label in F.LABELS if label != "unattributed"]
        lines += ["", "### Level 2 (pooled share)", ""]
        lines += ["| condition | " + " | ".join(labels) + " |", "|---|" + "---|" * len(labels)]
        for condition, c in cell.groupby("condition_id", sort=True):
            l2 = c[c["level"] == "L2"].set_index("measure")
            lines.append(f"| {condition} | " + " | ".join(F.pct(l2.loc[label, "share"]) for label in labels) + " |")
        lines.append("")

    conv = table[table["seed_set"] == "converged"]
    lines += [
        "## Runs that never trained (CLAUDE7.md hard rule 6)",
        "",
    ]
    if conv.empty:
        lines += ["No cell contains a run that never trained.", ""]
    else:
        lines += [
            "These cells include seeds whose source model never fit its training data "
            "(`reports/baselines.md`). The headline above keeps them; this table shows the same cells "
            "without them.",
            "",
            "| task | encoder | condition | failures (all → converged) | "
            "unattributed | linguistic | data | model |",
            "|---|---|---|---|---|---|---|---|",
        ]
        for (task, encoder, condition), c in conv.groupby(["task", "encoder", "condition_id"]):
            a = all_[(all_["task"] == task) & (all_["encoder"] == encoder) & (all_["condition_id"] == condition)]
            a1 = a[a["level"] == "L1"].set_index("measure")
            c1 = c[c["level"] == "L1"].set_index("measure")
            cells = [f"{F.pct(a1.loc[g, 'share'])} → {F.pct(c1.loc[g, 'share'])}" for g in F.GROUPS]
            lines.append(
                f"| {task} | {encoder} | {condition} | {int(a1['n_failures'].iloc[0]):,} → "
                f"{int(c1['n_failures'].iloc[0]):,} | " + " | ".join(cells) + " |"
            )
        lines.append("")
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    require_python()
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--n-boot", type=int, default=F.DEFAULT_N_BOOT)
    args = parser.parse_args(argv)

    table, problems = build(args.n_boot)
    config_hash = F.run_config_hash(n_boot=args.n_boot)
    table["config_hash"] = config_hash
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    table.to_parquet(OUT_DIR / "label_shares.parquet", index=False)
    (OUT_DIR / "label_shares.md").write_text(render(table, config_hash) + "\n")
    print(f"wrote {OUT_DIR / 'label_shares.parquet'} ({len(table)} rows), config {config_hash}")

    if problems:
        print(f"\n{len(problems)} problem(s):", file=sys.stderr)
        for p in problems:
            print(f"  {p}", file=sys.stderr)
        return 1
    print("all 72 cells present, reconciled with data/failures, shares sum to 100%")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
